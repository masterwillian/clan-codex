alter table public.trade_items
  add column if not exists unit_price numeric(18,2),
  add column if not exists rarity_multiplier numeric(8,4),
  add column if not exists rank_points numeric(20,4);

create or replace function public.stamp_trade_item_rank_snapshot()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_price numeric(18,2);
  v_multiplier numeric(8,4);
begin
  select p.price into v_price
  from public.pokemon_prices p
  where p.pokemon_id = new.pokemon_id;

  v_price := coalesce(v_price, 0);

  v_multiplier := case new.rarity
    when 'uncommon'::public.rarity then 1.00
    when 'rare'::public.rarity then 1.85
    when 'epic'::public.rarity then 2.12
    when 'legendary'::public.rarity then 2.81
    else 1.00
  end;

  -- O snapshot fica preso à troca criada. Mudanças futuras na tabela de preços
  -- não alteram a pontuação histórica.
  if new.unit_price is null then
    new.unit_price := v_price;
  end if;
  if new.rarity_multiplier is null then
    new.rarity_multiplier := v_multiplier;
  end if;
  if new.rank_points is null then
    new.rank_points := (new.unit_price / 1000.0) * new.rarity_multiplier * coalesce(new.quantity, 1);
  end if;

  return new;
end;
$$;

drop trigger if exists trade_items_stamp_rank_snapshot on public.trade_items;
create trigger trade_items_stamp_rank_snapshot
before insert on public.trade_items
for each row execute procedure public.stamp_trade_item_rank_snapshot();

